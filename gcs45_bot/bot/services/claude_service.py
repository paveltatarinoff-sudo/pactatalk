def _transliterate_name_to_latin(value: str) -> str:
    return "".join(_CYRILLIC_NAME_MAP.get(ch, ch) for ch in value.lower())


def _transliterate_name_to_cyrillic(value: str) -> str:
    transliterated = value.lower()
    transliterated = re.sub(r"([bcdfghjklmnpqrstvwxyz])ya", r"\1я", transliterated)
    transliterated = re.sub(r"([bcdfghjklmnpqrstvwxyz])yu", r"\1ю", transliterated)
    transliterated = re.sub(r"([bcdfghjklmnpqrstvwxyz])yo", r"\1ё", transliterated)
    transliterated = re.sub(r"([bcdfghjklmnpqrstvwxyz])ye", r"\1е", transliterated)
    for latin, cyr in _LATIN_NAME_MULTI:
        transliterated = transliterated.replace(latin, cyr)
    return "".join(_LATIN_NAME_SINGLE.get(ch, ch) for ch in transliterated)


def _name_variants(name: str) -> set[str]:
    cleaned = " ".join(name.strip().split())
    if not cleaned:
        return set()
    first_token = re.split(r"[\s,;/|]+", cleaned, maxsplit=1)[0]
    variants = {cleaned, first_token}
    expanded: set[str] = set()
    for item in variants:
        if not item:
            continue
        expanded.add(item)
        expanded.add(_transliterate_name_to_latin(item))
        expanded.add(_transliterate_name_to_cyrillic(item))
    return {variant for variant in expanded if variant}


class ClaudeService:
    MAX_CONSECUTIVE_BOTH_TURNS = 2

    def __init__(self) -> None:
        self._client = AsyncOpenAI(api_key=settings.openai_api_key)

    @staticmethod
    def _starts_with_partner_name(message: str, partner_name: str) -> bool:
        stripped = message.strip()
        candidates = sorted(_name_variants(partner_name), key=len, reverse=True)
        if not stripped or not candidates:
            return False
        for candidate in candidates:
            prefix_pattern = rf"(^|[.!?\n]\s*){re.escape(candidate)}\s*[:,]"
            suffix_vocative_pattern = rf"[,;:]\s*{re.escape(candidate)}\s*(?:[?!.]|$)"
            if (
                re.search(prefix_pattern, stripped, flags=re.IGNORECASE)
                or re.search(suffix_vocative_pattern, stripped, flags=re.IGNORECASE)
            ):
                return True
        return False

    async def _with_retry(self, operation: str, func, *, session_id: str | None = None):
        last_error: Exception | None = None

        for attempt in range(1, settings.openai_max_retries + 1):
            try:
                return await func()
            except (RateLimitError, APIConnectionError, APITimeoutError) as exc:
                last_error = exc
                retry_in = settings.openai_retry_base_delay_seconds * attempt + random.uniform(0, 0.5)
                log.warning(
                    "openai_retryable_error",
                    operation=operation,
                    session_id=session_id,
                    attempt=attempt,
                    retry_in=round(retry_in, 2),
                    error_type=exc.__class__.__name__,
                )
                if attempt >= settings.openai_max_retries:
                    break
                await asyncio.sleep(retry_in)
            except APIStatusError as exc:
                last_error = exc
                retryable = exc.status_code >= 500 or exc.status_code == 429
                log.warning(
                    "openai_status_error",
                    operation=operation,
                    session_id=session_id,
                    attempt=attempt,
                    status_code=exc.status_code,
                    retryable=retryable,
                )
                if not retryable or attempt >= settings.openai_max_retries:
                    break
                retry_in = settings.openai_retry_base_delay_seconds * attempt + random.uniform(0, 0.5)
                await asyncio.sleep(retry_in)
            except APIError as exc:
                last_error = exc
                log.exception(
                    "openai_api_error",
                    operation=operation,
                    session_id=session_id,
                    attempt=attempt,
                    error_type=exc.__class__.__name__,
                )
                break

        raise OpenAIServiceError.from_exception(last_error)

    def _developer_prompt(self, session: SessionState) -> str:
        """Динамический контекст диалога для GPT (без привязки к времени)."""
        return self._developer_prompt_for_state(session, session.dialogue_state)

    @classmethod
    def _recent_handoff_context(cls, messages: list[dict], limit: int = 6) -> str:
        """Build a short summary of recent speaker turns for handoff awareness."""
        turns: list[str] = []
        for item in reversed(messages):
            role = item.get("role", "")
            content = item.get("content", "")
            if role == "user":
                parsed = cls._extract_user_turn(content)
                if parsed:
                    speaker, text = parsed
                    short = text[:40].replace("\n", " ")
                    turns.append(f"  [{speaker}]: {short}...")
            elif role == "assistant":
                short = content[:40].replace("\n", " ")
                turns.append(f"  [BOT]: {short}...")
            if len(turns) >= limit:
                break
        if not turns:
            return ""
        turns.reverse()
        return "Последние ходы (для handoff awareness):\n" + "\n".join(turns) + "\n"

